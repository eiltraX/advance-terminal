"use strict";
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('src/renderer/index.html');
const js=read('src/renderer/v7-settings-expand.js');
const css=read('src/renderer/v7-settings-expand.css');
assert(html.includes('href="./v7-settings-expand.css"'));
assert(html.includes('src="./v7-settings-expand.js"'));
assert.equal((html.match(/id="settings-view"/g)||[]).length,1);
assert(js.includes("event.clientX - drag.x"),'Drag distance must control width');
assert(js.includes("panel.dataset.section === 'settings'"),'Only Settings has a resize handle');
assert(js.includes('pointercancel') && js.includes('lostpointercapture'),'Pointer cancellation must be handled');
assert(js.includes('aria-valuenow') && js.includes('ArrowRight'),'Keyboard resize should be accessible');
assert(js.includes('requestAnimationFrame'),'Resize updates must be frame-limited');
assert(js.includes('terminalReserve'),'Preserve visible terminal width');
assert(!js.includes('v7-settings-expand-toggle'),'Remove old Expand/Restore button');
assert(!/window\.advanceTerminal|ipcRenderer|writeTerminal|saveSettings|restorePoints/.test(js),'UI-only resize must not invoke privileged APIs');
assert(css.includes('grid-template-columns') && css.includes('v7-settings-resize-handle'));
console.log('PASS: Settings divider drag, width limits, keyboard controls and reset.');
console.log('PASS: Existing settings DOM/IDs preserved; no expand button or privileged operations.');
