"use strict";
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('src/renderer/index.html');
const css=read('src/renderer/v7-settings-neutral-ui07.css');
const js=read('src/renderer/v7-settings-expand.js');
assert.equal((html.match(/v7-settings-neutral-ui07.css/g)||[]).length,1,'Single new CSS link');
assert(html.includes('<h3>Application Update</h3>'),'Approved update heading');
for(const id of ['at-settings-search','update-current-version','update-status-message','update-status-pill','check-updates-button','install-update-button'])assert(html.includes(`id="${id}"`),`Required control missing: ${id}`);
assert(js.includes('const DEFAULT_SETTINGS_WIDTH = 680;'),'Default Settings width is 680px');
assert(js.includes('else applyWidth(DEFAULT_SETTINGS_WIDTH, false);'),'Open/resize must initialize default width');
assert(js.includes('handle.addEventListener(\'pointerdown\'') && js.includes("event.clientX - drag.x"),'Resizing retained');
assert(js.includes('savedWidth = null;\n      applyWidth(DEFAULT_SETTINGS_WIDTH, false);'),'Double click resets to default width');
assert(css.includes('background: #252a30'),'Dark Updates fields');
assert(css.includes('padding: 6px 10px 6px 33px'),'Search icon/text clearance');
assert(css.includes('border: 1px solid transparent'),'Neutral navigation item border');
assert(css.includes('prefers-reduced-motion'),'Reduced motion');
assert(!/ipcRenderer|writeTerminal|saveSettings|restorePoints/.test(js),'No privileged API added to resize');
console.log('PASS: UI07 fields, search, neutral selection and 680px default source guards.');
